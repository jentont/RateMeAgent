def _anchor_ts(label: str) -> float:
    year, month = (int(part) for part in label.split("-"))
    return time.mktime((year, month, 1, 0, 0, 0, 0, 1, -1))


def registered_at(user_id: int) -> float:
    """Когда примерно человек завёл Telegram, unix-время.

    Линейная интерполяция между опорными точками. За краями таблицы
    берём крайние значения: у самых первых аккаунтов дата всё равно
    «очень давно», а у самых свежих — «только что».
    """
    anchors = ID_ANCHORS
    if user_id <= anchors[0][0]:
        return _anchor_ts(anchors[0][1])
    for (low_id, low_at), (high_id, high_at) in zip(anchors, anchors[1:]):
        if user_id <= high_id:
            low_ts, high_ts = _anchor_ts(low_at), _anchor_ts(high_at)
            k = (user_id - low_id) / (high_id - low_id)
            return low_ts + (high_ts - low_ts) * k
    # За последней опорой продолжаем последним известным темпом.
    (prev_id, prev_at), (last_id, last_at) = anchors[-2], anchors[-1]
    prev_ts, last_ts = _anchor_ts(prev_at), _anchor_ts(last_at)
    speed = (last_ts - prev_ts) / max(1, last_id - prev_id)
    return last_ts + (user_id - last_id) * speed

DAY = 86400

#: Вокруг какого балла растягивается итог. Пять с половиной — середина
#: живой шкалы: столько набирает обычный профиль с аватаркой и ником.
PIVOT = 5.5


@dataclass(slots=True)
class Profile:
    """Снимок профиля, из которого считается балл.

    Ровно то, что рисуется на карточке: пересчитать балл из снимка можно
    и через месяц, не ходя в Telegram заново.
    """

    user_id: int
    username: str | None
    name: str
    photos: int = 0
    bio: str = ""
    gifts: int = 0
    nft: int = 0
    stars: int = 0
    level: int = 0
    joined_at: int = 0
    #: Ник куплен на Fragment, а не занят обычным способом.
    nft_name: bool = False
    #: Во сколько рынок оценивает сам ник, $. Ноль — не продавался.
    name_usd: float = 0.0
    #: Самый редкий признак среди NFT-подарков: «Чёрный (фон)».
    rare_name: str = ""
    #: Его редкость, 0..1 — см. mtproto._rarity_score.
    rarity: float = 0.0
    #: Качество самой аватарки, 0..1 — см. photo.py.
    avatar_quality: float = 0.0
    #: Байты аватарки. В базу не пишутся, живут только на время отрисовки.
    avatar: bytes | None = None
    #: Какие поля пришли из MTProto, а какие досчитаны от id.
    guessed: tuple[str, ...] = ()

    @property
    def usd(self) -> float:
        return self.stars * config.USD_PER_STAR

    @property
    def handle(self) -> str:
        return f"@{self.username}" if self.username else "без юзернейма"


def _clamp(value: float, low: float = 1.0, high: float = 9.9) -> float:
    return max(low, min(high, value))


def _jitter(user_id: int, key: str) -> float:
    """Микросдвиг ±0.12 балла, свой у каждой пары «человек + метрика».

    Нужен против ничьих: два свежих аккаунта без аватарки и подарков
    дают одинаковые числа во всех семи строках, и карточка получается
    без победителя. Сдвиг детерминированный — при повторном баттле те же
    цифры, «перекатать» результат нельзя.
    """
    digest = hashlib.sha256(f"{user_id}:{key}".encode()).digest()
    return (int.from_bytes(digest[:4], "big") / 0xFFFFFFFF - 0.5) * 0.24


#: Потолок метрики «Аватар». Ниже общего потолка шкалы намеренно.
#:
#: Резкую фотографию ставит кто угодно за минуту, а NFT на пять тысяч
#: долларов — нет. Пока идеальный кадр давал 9.90, а коллекция на $5000
#: только 7.83, пустой аккаунт с одной хорошей аватаркой обыгрывал
#: коллекционера — и это ровно то, на что жаловались.
#:
#: Метрика не обесценена: от 2.6 без фото до 8.2 за отличное — разброс
#: почти шесть баллов, больше любой другой. Просто её верх больше не
#: спорит с настоящими деньгами.
AVATAR_FLOOR = 3.0
AVATAR_RANGE = 4.8
AVATAR_GALLERY = 0.4
AVATAR_TOP = AVATAR_FLOOR + AVATAR_RANGE + AVATAR_GALLERY


def score_avatar(p: Profile) -> float:
    """Аватарка: важно какая, а не сколько их.

    Раньше метрика считала фотографии — чем больше, тем выше балл.
    Человек с одним хорошим снимком проигрывал тому, кто залил двадцать
    размытых, а накручивалось это за минуту. Теперь основа — качество
    самого кадра (резкость, детализация, контраст, цвет), а количество
    осталось небольшой добавкой: галерея чуть лучше одного снимка, но
    решает не она.
    """
    if "avatar" in p.guessed:
        # Посмотреть не удалось ни боту, ни сборщику: аватарка закрыта
        # приватностью или поставлена коллекционным подарком. Это не
        # «плохая аватарка» и не «её нет», поэтому ставим нижнюю границу
        # читаемых — не наказывая, но и не награждая за закрытость.
        return _clamp(AVATAR_FLOOR + _jitter(p.user_id, "avatar"))
    if p.photos <= 0 and p.avatar_quality <= 0:
        return _clamp(2.6 + _jitter(p.user_id, "avatar"))

    # Фото есть, а качества нет — значит не измерили: аватарка не
    # скачалась или Telegram не отдал файл. Это не «плохой снимок», и
    # ставить за него как за мыло нечестно, поэтому берём середину.
    quality = p.avatar_quality if p.avatar_quality > 0 else 0.5
    base = AVATAR_FLOOR + AVATAR_RANGE * max(0.0, min(1.0, quality))
    # Добавка за галерею: маленькая и логарифмическая. Галерея чуть
    # лучше одного снимка, но решает не она — и накручивается за минуту.
    base += min(AVATAR_GALLERY, 0.14 * math.log2(1 + max(0, p.photos)))
    return _clamp(base + _jitter(p.user_id, "avatar"), 1.0, AVATAR_TOP)


def score_username(p: Profile) -> float:
    """Сколько имя стоит: сперва по качеству, потом по рынку.

    Метрика была линейкой `9.8 − 0.35 × длина`, и по ней `@kwjpz` получал
    ровно столько же, сколько `@storm`: пять букв есть пять букв. Рынок
    так не считает — покупают не короткие строки, а слова, — и случайный
    набор согласных забирал восемь баллов ни за что.

    Основа теперь — разбор самого имени (см. naming.py): словарное ли
    оно, произносимое, короткое, без цифр. Поверх ложится цена с
    Fragment, если имя оттуда: `@auto` за сорок тысяч долларов и мусор,
    ушедший за минимальную ставку, оба коллекционные, но стоить одинаково
    не могут.

    Отсутствие юзернейма — почти дно шкалы: без него человека нельзя ни
    упомянуть, ни найти.
    """
    if not p.username:
        return _clamp(2.2 + _jitter(p.user_id, "username"))

    # Красотой одной девятку не взять: потолок разбора — восемь с
    # небольшим. Выше поднимает только цена, и это честно: верх шкалы
    # должен стоить денег, а не удачного набора букв.
    base = 2.6 + 5.6 * naming.appeal(p.username)
    # Сам факт аукциона — небольшая надбавка: имя не досталось даром.
    if p.nft_name:
        base += 0.5

    # Цена не складывается с разбором, а заменяет его, когда выше.
    # Разбор — это догадка о цене, а тут цена известна: `@qq` не слово и
    # не читается, но ушёл за десятки тысяч, и спорить с рынком не о чем.
    # Складывать эти два числа значило бы считать одно и то же дважды.
    if p.name_usd > 0:
        base = max(base, 3.2 + 1.5 * math.log10(1 + p.name_usd))
    return _clamp(base + _jitter(p.user_id, "username"))


def score_bio(p: Profile) -> float:
    """Описание: важен сам факт, а не попадание в идеальную длину.

    Кривая из трёх кусков: быстрый рост от нуля до сорока символов,
    дальше плато, и лишь после ста шестидесяти — мягкий спад за простыню.

    Прежняя версия искала пик ровно на девяноста символах и наказывала
    отклонение в обе стороны: живая строка «сдвг порно-аутист» получала
    меньше, чем случайный набор нужной длины. Так себе метрика — люди
    пишут о себе коротко и это нормально.
    """
    n = len((p.bio or "").strip())
    if n == 0:
        return _clamp(2.9 + _jitter(p.user_id, "bio"))
    if n < 40:
        base = 5.2 + 0.085 * n
    elif n <= 160:
        base = 8.6
    else:
        base = 8.6 - min(2.4, (n - 160) / 300 * 2.4)

    # Рекламный щит вместо описания — минус до четырёх баллов. Строка из
    # прайса и трёх ссылок не должна выигрывать у живого «сдвг
    # порно-аутист» только потому, что она длиннее.
    base -= bio_spam(p.bio or "") * 4.0
    return _clamp(base + _jitter(p.user_id, "bio"), 1.0, 9.4)


def score_gifts(p: Profile) -> float:
    """Подарки считаются штуками, NFT — отдельной надбавкой.

    NFT-подарок стоит на порядок дороже обычного и достаётся сложнее,
    поэтому один такой весит примерно как удвоение обычной коллекции.

    Редкость признаков — третья составляющая. Уникальный подарок
    собирается из случайных модели, фона и узора: чёрный фон достаётся
    полутора экземплярам из тысячи, серый — каждому десятому. Одинаковые
    с виду коллекции стоят на рынке по-разному именно из-за этого.
    """
    if p.gifts <= 0 and p.nft <= 0:
        return _clamp(3.0 + _jitter(p.user_id, "gifts"))
    base = 4.1 + 0.46 * math.log2(1 + p.gifts) + 0.35 * math.log2(1 + p.nft)
    base += 1.2 * max(0.0, min(1.0, p.rarity))
    return _clamp(base + _jitter(p.user_id, "gifts"))


def score_value(p: Profile) -> float:
    """Стоимость коллекции в долларах, шкала логарифмическая.

    По линейной шкале один человек с дорогим подарком забирал бы метрику
    целиком, а разница между $0 и $20 — которая и есть у большинства —
    не читалась бы вовсе.
    """
    usd = p.usd
    if usd <= 0:
        return _clamp(3.0 + _jitter(p.user_id, "value"))
    # Кривая круче прежней почти вдвое. Была настолько пологой, что
    # пятьдесят тысяч долларов давали 8.65 — меньше, чем бесплатная
    # резкая фотография. Теперь $1000 это 8.5, а $5000 — почти потолок:
    # столько в подарках держат единицы, и метрика обязана это показать.
    return _clamp(4.2 + 1.45 * math.log10(1 + usd) + _jitter(p.user_id, "value"))


#: Что выдаёт рекламное описание. Ловим не слова целиком, а куски:
#: «реклам» покрывает и «рекламу», и «рекламное».
AD_MARKS = (
    "реклам", "куплю", "продам", "продаю", "прайс", "сотруднич", "заказ",
    "прайс-лист", "услуг", "скидк", "промокод", "подписыв", "подпишись",
    "канал:", "чат:", "по всем вопросам", "в лс", "пиши в", "работа",
    "заработ", "доход", "инвест", "крипт", "ставк", "казино", "нарко",
    "оптом", "дешев", "дёшев", "бот:", "магазин", "shop", "price",
    "promo", "subscribe", "casino", "invest",
)


def bio_spam(text: str) -> float:
    """Насколько описание похоже на рекламный щит, 0..1.

    Считаем не по одному признаку, а по сумме: ссылки, упоминания чужих
    каналов, торговые слова и капс. Одна ссылка на свой канал — норма,
    три ссылки вперемешку с «прайс» и «в лс» — уже вывеска.
    """
    if not text:
        return 0.0
    low = text.lower()
    score = 0.0

    links = low.count("t.me/") + low.count("http") + low.count("@")
    score += min(0.45, links * 0.15)

    hits = sum(1 for mark in AD_MARKS if mark in low)
    score += min(0.45, hits * 0.15)

    letters = [ch for ch in text if ch.isalpha()]
    if len(letters) >= 12:
        caps = sum(1 for ch in letters if ch.isupper()) / len(letters)
        if caps > 0.6:
            score += 0.15

    return min(1.0, score)


def score_registered(p: Profile) -> float:
    """Возраст аккаунта в Telegram — по номеру, а не по нашей базе.

    Метрика, которую нельзя накрутить вообще ничем: id выдаётся один раз
    при регистрации. Старый аккаунт с трёхзначным id ценится ровно за то,
    что человек здесь с самого начала.
    """
    years = max(0.0, (time.time() - registered_at(p.user_id)) / (DAY * 365.25))
    # Шкала растягивается на весь возраст мессенджера, а не на жёсткие
    # 0.55 балла за год. С фиксированным шагом всё, что старше 2014-го,
    # упиралось в потолок и выглядело одинаково: аккаунт с запуска не
    # отличался от заведённого через полтора года. А с каждым новым годом
    # в потолок утыкалось бы ещё больше людей.
    return _clamp(3.0 + 6.9 * min(1.0, years / _telegram_age()), 1.0, 9.9)


def _telegram_age() -> float:
    """Сколько лет самому Telegram — верх шкалы «Регистрация»."""
    return max(1.0, (time.time() - _anchor_ts(ID_ANCHORS[0][1])) / (DAY * 365.25))


def score_level(p: Profile) -> float:
    """Уровень Telegram — тот самый, что растёт от подарков и премиума.

    Нулевой уровень стоил пять баллов — ровно столько же, сколько
    середина шкалы. Пустой профиль получал их даром, и метрика, которую
    без подарков не поднять, никого ни от кого не отличала.
    """
    return _clamp(3.2 + 0.52 * max(0, p.level), 1.0, 9.9)


